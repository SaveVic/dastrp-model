"""
tools/convert_imbd_esr.py
=========================
Convert the public IMBD-ESR release into the processed layout that
DASTRP-Net's data loader (data/dataset.py) and the YOLO detector expect.

Public IMBD-ESR layout (input, see DATA_FORMAT.md in the dataset repo):

    imbd-esr/
      annotations/
        split_result.json
        {domain}/{video}/meta.json
        {domain}/{video}/tracks/{video}_{frame:06d}.json
      videos/
        {domain}/{video}.mp4

Processed layout (output):

    dataset/
      train/ val/ test/
        images/  {video}__{frame:06d}.jpg
        labels/  {video}__{frame:06d}.txt   (YOLO: class cx cy w h)
        tracks/  {video}__{frame:06d}.json  (objects for DASTRP-Net)
        meta.json
      class_names.txt
      dataset.yaml

Frame selection mirrors the pipeline used in the paper
(tools/prepare_dataset.py):
  * train    : annotated frames, expanded by +/- `margin` frames, plus a
               random `bg_ratio` fraction of the remaining frames (seeded)
  * val/test : every frame of the video

Usage
-----
  # DASTRP-Net format (2 classes: gerak/diam, + risk labels in tracks/)
  python tools/convert_imbd_esr.py \
      --src  /path/to/imbd-esr \
      --dst  /path/to/dataset/dastrp

  # YOLO detector format (single class "motor")
  python tools/convert_imbd_esr.py \
      --src  /path/to/imbd-esr \
      --dst  /path/to/dataset/yolo \
      --mode yolo
"""

import argparse
import json
import random
from collections import defaultdict
from pathlib import Path

import cv2
from tqdm import tqdm

RISK_STR = {0: "safe", 1: "warning", 2: "danger"}
MOTION_STR = {0: "gerak", 1: "diam"}

YAML_DASTRP = """\
# Dataset config for DASTRP-Net (generated by tools/convert_imbd_esr.py)
path: {root}
train: train/images
val:   val/images
test:  test/images
nc: 2
names:
  0: gerak
  1: diam
"""

YAML_YOLO = """\
# Dataset config for the YOLO motorcycle detector
# (generated by tools/convert_imbd_esr.py)
path: {root}
train: train/images
val:   val/images
test:  test/images
nc: 1
names:
  0: motor
"""


def _clamp(v: float) -> float:
    return max(0.0, min(1.0, float(v)))


def select_frames(meta: dict, split: str, margin: int, bg_ratio: float,
                  seed: int) -> list:
    """Return the sorted list of frame indices to export for one video."""
    all_idx = [int(fr["frame_idx"]) for fr in meta["frames"]]
    if split != "train":
        return sorted(all_idx)

    lo, hi = min(all_idx), max(all_idx)
    annotated = {int(fr["frame_idx"]) for fr in meta["frames"]
                 if fr.get("has_annotation") and fr.get("n_objects", 0) > 0}

    active = set()
    for f in annotated:
        active.update(range(max(lo, f - margin), min(hi, f + margin) + 1))

    background = sorted(set(all_idx) - active)
    random.seed(seed)
    n_bg = int(len(background) * bg_ratio)
    sampled = set(random.sample(background, n_bg)) if n_bg else set()
    return sorted(active | sampled)


def load_track(track_dir: Path, video: str, frame_idx: int) -> list:
    """Load objects of one frame from the public format ([] if none)."""
    path = track_dir / f"{video}_{frame_idx:06d}.json"
    if not path.exists():
        return []
    with open(path) as f:
        return json.load(f).get("objects", [])


def convert_video(video: str, split: str, domain: str, src: Path,
                  out_split: Path, mode: str, margin: int, bg_ratio: float,
                  seed: int, quality: int) -> dict:
    vid_dir = src / "annotations" / domain / video
    with open(vid_dir / "meta.json") as f:
        meta = json.load(f)

    video_path = src / "videos" / domain / f"{video}.mp4"
    if not video_path.exists():
        raise FileNotFoundError(f"Video not found: {video_path}")

    frames = select_frames(meta, split, margin, bg_ratio, seed)
    wanted = set(frames)

    img_dir = out_split / "images"
    lbl_dir = out_split / "labels"
    trk_dir = out_split / "tracks"
    for d in (img_dir, lbl_dir) + ((trk_dir,) if mode == "dastrp" else ()):
        d.mkdir(parents=True, exist_ok=True)

    stats = defaultdict(int)
    stats["video"] = video
    cap = cv2.VideoCapture(str(video_path))
    cur = min(frames)
    cap.set(cv2.CAP_PROP_POS_FRAMES, cur)
    pbar = tqdm(total=len(frames), desc=f"  {video} [{split}]", leave=False)

    while cur <= max(frames):
        ok, frame = cap.read()
        if not ok:
            break
        if cur in wanted:
            stem = f"{video}__{cur:06d}"
            cv2.imwrite(str(img_dir / f"{stem}.jpg"), frame,
                        [cv2.IMWRITE_JPEG_QUALITY, quality])

            objs = load_track(vid_dir / "tracks", video, cur)
            yolo_lines, track_objs = [], []
            for i, o in enumerate(objs):
                cx, cy, w, h = (_clamp(v) for v in o["bbox"])
                motion = int(o.get("motion", 0))
                risk = int(o.get("risk", 0))
                cls = 0 if mode == "yolo" else motion
                yolo_lines.append(f"{cls} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}")
                track_objs.append({
                    "idx": i, "id": o.get("id"),
                    "label": MOTION_STR[motion], "class_id": motion,
                    "risk": RISK_STR[risk], "risk_id": risk,
                    "cx": round(cx, 6), "cy": round(cy, 6),
                    "w": round(w, 6), "h": round(h, 6),
                })
                stats[f"risk_{RISK_STR[risk]}"] += 1
                stats[f"objects_{MOTION_STR[motion]}"] += 1

            with open(lbl_dir / f"{stem}.txt", "w") as f:
                f.write("\n".join(yolo_lines) + ("\n" if yolo_lines else ""))
            if mode == "dastrp":
                with open(trk_dir / f"{stem}.json", "w") as f:
                    json.dump({"video": video, "frame": cur,
                               "objects": track_objs}, f)

            stats["frames_selected"] += 1
            stats["frames_with_obj" if objs else "frames_empty"] += 1
            pbar.update(1)
        cur += 1

    pbar.close()
    cap.release()
    return dict(stats)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", required=True,
                    help="Root of the IMBD-ESR release (contains annotations/ and videos/)")
    ap.add_argument("--dst", required=True, help="Output dataset root")
    ap.add_argument("--mode", choices=["dastrp", "yolo"], default="dastrp")
    ap.add_argument("--split-file", default=None,
                    help="Override split file (default: <src>/annotations/split_result.json)")
    ap.add_argument("--margin", type=int, default=16)
    ap.add_argument("--bg-ratio", type=float, default=0.1)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--quality", type=int, default=100, help="JPEG quality")
    args = ap.parse_args()

    src, dst = Path(args.src), Path(args.dst)
    split_file = Path(args.split_file) if args.split_file else \
        src / "annotations" / "split_result.json"
    with open(split_file) as f:
        split_info = json.load(f)

    assignment = split_info.get("assignment", split_info)
    per_video = split_info.get("per_video", {})

    by_split = defaultdict(list)
    for video, split in sorted(assignment.items()):
        by_split[split].append(video)

    for split in ("train", "val", "test"):
        if not by_split.get(split):
            continue
        out_split = dst / split
        print(f"[{split}] {len(by_split[split])} video(s)")
        split_stats = []
        for video in by_split[split]:
            domain = per_video.get(video, {}).get("domain", video.split("_")[0])
            split_stats.append(convert_video(
                video, split, domain, src, out_split, args.mode,
                args.margin, args.bg_ratio, args.seed, args.quality))
        with open(out_split / "meta.json", "w") as f:
            json.dump({"split": split, "videos": split_stats}, f, indent=2)

    with open(dst / "class_names.txt", "w") as f:
        f.write("motor\n" if args.mode == "yolo" else "gerak\ndiam\n")
    with open(dst / "dataset.yaml", "w") as f:
        tpl = YAML_YOLO if args.mode == "yolo" else YAML_DASTRP
        f.write(tpl.format(root=str(dst.resolve())))
    print(f"Done -> {dst}")


if __name__ == "__main__":
    main()
